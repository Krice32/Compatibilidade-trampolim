export function normalizeCourseName(value = '') {
  return String(value).normalize('NFD').replace(/[\u0300-\u036f]/g, '').toLowerCase().replace(/[^a-z0-9]+/g, ' ').trim()
}

function levenshtein(first, second) {
  const previous = Array.from({ length: second.length + 1 }, (_, index) => index)
  for (let row = 1; row <= first.length; row += 1) {
    const current = [row]
    for (let column = 1; column <= second.length; column += 1) {
      const substitution = previous[column - 1] + (first[row - 1] === second[column - 1] ? 0 : 1)
      current[column] = Math.min(current[column - 1] + 1, previous[column] + 1, substitution)
    }
    previous.splice(0, previous.length, ...current)
  }
  return previous[second.length]
}

function textSimilarity(first, second) {
  const normalizedFirst = normalizeCourseName(first)
  const normalizedSecond = normalizeCourseName(second)
  if (!normalizedFirst || !normalizedSecond) return 0
  if (normalizedFirst === normalizedSecond) return 1
  if (normalizedSecond.includes(normalizedFirst) || normalizedFirst.includes(normalizedSecond)) return .92
  const characterScore = 1 - (levenshtein(normalizedFirst, normalizedSecond) / Math.max(normalizedFirst.length, normalizedSecond.length))
  const queryWords = normalizedFirst.split(' ')
  const targetWords = normalizedSecond.split(' ')
  const wordScore = queryWords.reduce((sum, queryWord) => sum + Math.max(...targetWords.map((targetWord) => 1 - (levenshtein(queryWord, targetWord) / Math.max(queryWord.length, targetWord.length)))), 0) / queryWords.length
  return Math.max(characterScore, wordScore * .88)
}

function levelFromText(value = '') {
  const normalized = normalizeCourseName(value)
  if (/\b(avancado|especialista|expert)\b/.test(normalized)) return 3
  if (/\bintermediario\b/.test(normalized)) return 2
  if (/\b(basico|iniciante|introducao|fundamentos)\b/.test(normalized)) return 1
  return 0
}

function subjectWithoutLevel(value = '') {
  return normalizeCourseName(value).replace(/\b(avancado|intermediario|basico|iniciante|especialista|expert|introducao|fundamentos)\b/g, '').replace(/\s+/g, ' ').trim()
}

export function matchComplementaryCourseEvidence(requiredCourse, evidence) {
  const requiredId = complementaryCourseId(requiredCourse)
  const evidenceId = complementaryCourseId(evidence)
  const requiredText = typeof requiredCourse === 'string' ? requiredCourse : requiredCourse?.name || ''
  const evidenceText = typeof evidence === 'string' ? evidence : [evidence?.name, evidence?.tool, evidence?.level, evidence?.description].filter(Boolean).join(' ')

  if (requiredId && evidenceId && requiredId === evidenceId) return { adherence: 1, matchType: 'shared-id' }
  if (!requiredText || !evidenceText) return { adherence: 0, matchType: 'none' }

  const requiredCatalogItem = complementaryCourseCatalog.find((item) => item.id === requiredId)
  const searchableRequirements = requiredCatalogItem ? [requiredCatalogItem.name, ...(requiredCatalogItem.aliases || [])] : [requiredText]
  const sameSubject = searchableRequirements.some((value) => subjectWithoutLevel(value) && subjectWithoutLevel(value) === subjectWithoutLevel(evidenceText))
  const similarity = Math.max(sameSubject ? .9 : 0, ...searchableRequirements.map((value) => textSimilarity(value, evidenceText)))
  if (similarity < .78) return { adherence: 0, matchType: 'none' }

  const requiredLevel = levelFromText(requiredText)
  const evidenceLevel = levelFromText(evidenceText)
  if (requiredLevel && evidenceLevel && evidenceLevel < requiredLevel) return { adherence: .5, matchType: 'related-lower-level' }
  if (requiredLevel && !evidenceLevel) return { adherence: .7, matchType: 'related-level-not-informed' }
  return { adherence: 1, matchType: 'semantic-evidence' }
}

export function searchComplementaryCourses(query = '') {
  const normalizedQuery = normalizeCourseName(query)
  if (!normalizedQuery) return complementaryCourseCatalog.slice(0, 12).map((item) => ({ ...item, matchScore: 1, fuzzy: false }))
  return complementaryCourseCatalog.map((item) => {
    const searchableValues = [item.name, ...(item.aliases || [])]
    const matchScore = Math.max(...searchableValues.map((value) => textSimilarity(query, value)))
    const direct = searchableValues.some((value) => normalizeCourseName(value).includes(normalizedQuery))
    return { ...item, matchScore, fuzzy: !direct }
  }).filter((item) => item.matchScore >= (normalizedQuery.length < 4 ? .62 : .46)).sort((first, second) => Number(first.fuzzy) - Number(second.fuzzy) || second.matchScore - first.matchScore || first.name.localeCompare(second.name, 'pt-BR')).slice(0, 10)
}

export function customComplementaryCourseId(name = '') {
  const normalized = normalizeCourseName(name)
  let hash = 2166136261
  for (const character of normalized) {
    hash ^= character.charCodeAt(0)
    hash = Math.imul(hash, 16777619)
  }
  return `CUSTOM-${(hash >>> 0).toString(16).toUpperCase().padStart(8, '0')}`
}

export function complementaryCourseId(item) {
  if (!item) return ''
  if (typeof item === 'string') return ''
  return item.catalogId || item.courseId || (/^(CUR|CUSTOM)-/.test(item.id || '') ? item.id : '')
}
